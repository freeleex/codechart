import { readFileSync } from 'node:fs';
import ts from 'typescript';

export const CLIENT_SOURCE = 'src/render/web/browser/client.ts';
/** Modules client.ts imports, in the order the page runs them. */
export const CLIENT_DEPS = ['src/render/web/browser/store.ts', 'src/render/web/browser/history.ts', 'src/render/web/browser/focus.ts', 'src/render/web/browser/chips.ts', 'src/render/web/browser/review.ts', 'src/render/web/browser/glide.ts', 'src/render/web/browser/resize.ts', 'src/render/web/browser/hunks.ts', 'src/render/web/browser/why.ts', 'src/render/web/browser/targets.ts', 'src/render/web/browser/note-store.ts', 'src/render/web/browser/note-view.ts', 'src/render/web/browser/note-paint.ts', 'src/render/web/browser/comments.ts', 'src/render/web/browser/finish.ts', 'src/render/web/browser/business-send.ts', 'src/render/web/browser/business.ts', 'src/render/web/browser/export.ts'];
export const CLIENT_OUTPUT = 'src/render/web/client.ts';

function transpile(file: string): string {
  return ts.transpileModule(readFileSync(file, 'utf8'), {
    compilerOptions: { target: ts.ScriptTarget.ES2018, module: ts.ModuleKind.ESNext, removeComments: true, newLine: ts.NewLineKind.LineFeed },
  }).outputText;
}

/** The browser script as the generated module's text: src/render/web/browser/*.ts without types, as one IIFE. */
export function buildClient(): string {
  // In the page the files share one scope, so their imports and exports go.
  const unlink = (src: string) => src.replace(/^import [^\n]*\n/gm, '').replace(/^export /gm, '');
  const deps = CLIENT_DEPS.map((f) => unlink(transpile(f)));
  const main = unlink(transpile(CLIENT_SOURCE));
  if (main.includes('import ') || deps.some((d) => /^(import|export) /m.test(d))) {
    throw new Error(`${CLIENT_SOURCE}: imports and exports must each sit on one line`);
  }
  const body = [...deps, main].join('\n');
  const lines = ['', '(function () {', ...body.trimEnd().split('\n'), '})();', ''];
  return `// Generated by scripts/gen-client.ts from src/render/web/browser/; edit those and run npm run gen:client.
export const CLIENT_JS = [
${lines.map((l) => `  ${JSON.stringify(l)},`).join('\n')}
].join('\\n');
`;
}
